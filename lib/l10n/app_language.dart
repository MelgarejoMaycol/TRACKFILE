import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

const String _languagePreferenceKey = 'trackfile_language';

class AppLanguage {
  final String code;
  final String name;
  final String nativeName;
  final String flag;

  const AppLanguage({
    required this.code,
    required this.name,
    required this.nativeName,
    required this.flag,
  });
}

class AppLanguageController extends ValueNotifier<Locale> {
  AppLanguageController._() : super(const Locale('es'));

  static final AppLanguageController instance = AppLanguageController._();

  static const supportedLanguages = <AppLanguage>[
    AppLanguage(
      code: 'es',
      name: 'Spanish',
      nativeName: 'Español',
      flag: '🇨🇴',
    ),
    AppLanguage(
      code: 'en',
      name: 'English',
      nativeName: 'English',
      flag: '🇺🇸',
    ),
    AppLanguage(
      code: 'fr',
      name: 'French',
      nativeName: 'Français',
      flag: '🇫🇷',
    ),
    AppLanguage(
      code: 'pt',
      name: 'Portuguese',
      nativeName: 'Português',
      flag: '🇧🇷',
    ),
    AppLanguage(
      code: 'it',
      name: 'Italian',
      nativeName: 'Italiano',
      flag: '🇮🇹',
    ),
  ];

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString(_languagePreferenceKey);
    value = Locale(_normalizeCode(saved));
  }

  Future<void> setLanguage(String code) async {
    final normalized = _normalizeCode(code);
    if (value.languageCode == normalized) return;

    value = Locale(normalized);
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_languagePreferenceKey, normalized);
  }

  AppLanguage get currentLanguage {
    return supportedLanguages.firstWhere(
      (language) => language.code == value.languageCode,
      orElse: () => supportedLanguages.first,
    );
  }

  static bool isSupported(String code) {
    return supportedLanguages.any((language) => language.code == code);
  }

  static String _normalizeCode(String? code) {
    final normalized = (code ?? 'es').toLowerCase().trim();
    return isSupported(normalized) ? normalized : 'es';
  }
}

extension AppLanguageContext on BuildContext {
  String t(String key) {
    return AppTranslations.text(key, AppLanguageController.instance.value);
  }

  String sectionLabel(String section) {
    return AppTranslations.section(section, AppLanguageController.instance.value);
  }
}

class AppTranslations {
  static String text(String key, Locale locale) {
    final language = locale.languageCode;
    return _values[language]?[key] ??
        _values['en']?[key] ??
        _values['es']?[key] ??
        key;
  }

  static String section(String section, Locale locale) {
    final key = 'section.${_sectionKey(section)}';
    return text(key, locale);
  }

